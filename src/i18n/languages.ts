export type SupportedLanguage = 'en' | 'ms' | 'zh';
export type AnyLanguageCode = SupportedLanguage | 'my' | 'cn' | 'MY' | 'CN' | 'EN';

export interface LanguageOption {
  code: SupportedLanguage;
  displayCode: string;
  label: string;
  flag: string;
  nativeName: string;
}

export function normalizeLanguageCode(code: string): SupportedLanguage {
  const lower = code.toLowerCase();
  if (lower === 'my' || lower === 'ms') return 'ms';
  if (lower === 'cn' || lower === 'zh') return 'zh';
  return 'en';
}

